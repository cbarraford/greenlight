# ---- the YAML subset -------------------------------------------------------------------------------------------

def front_matter(text):
    """The YAML between the opening `---` and the next `---` line."""
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        raise ValueError("DESIGN.md has no YAML front matter")
    return m.group(1)


def strip_comment(line):
    """Drop a ` # comment` that sits outside quotes."""
    quote = None
    for i, ch in enumerate(line):
        if quote:
            quote = None if ch == quote else quote
        elif ch in "\"'":
            quote = ch
        elif ch == "#" and (i == 0 or line[i - 1] in " \t"):
            return line[:i].rstrip()
    return line.rstrip()


def split_top(s, sep=","):
    """Split on `sep` outside quotes and brackets."""
    parts, depth, quote, cur = [], 0, None, ""
    for ch in s:
        if quote:
            quote = None if ch == quote else quote
        elif ch in "\"'":
            quote = ch
        elif ch in "[{":
            depth += 1
        elif ch in "]}":
            depth -= 1
        elif ch == sep and depth == 0:
            parts.append(cur.strip())
            cur = ""
            continue
        cur += ch
    if cur.strip():
        parts.append(cur.strip())
    return parts


def scalar(s):
    """A flow value: list, map, quoted string, number, or bare string."""
    s = s.strip()
    if s.startswith("[") and s.endswith("]"):
        return [scalar(p) for p in split_top(s[1:-1])]
    if s.startswith("{") and s.endswith("}"):
        return dict(key_value(p) for p in split_top(s[1:-1]))
    if len(s) >= 2 and s[0] == s[-1] and s[0] in "\"'":
        return s[1:-1]
    for cast in (int, float):
        try:
            return cast(s)
        except ValueError:
            pass
    return s


def key_value(s):
    """`key: value` → (key, value); the key may be quoted."""
    m = re.match(r"""\s*("[^"]*"|'[^']*'|[^:]+?)\s*:(?:\s+(.*)|\s*$)""", s)
    if not m:
        raise ValueError(f"not a key: value pair: {s!r}")
    key = m.group(1).strip("\"'")
    return key, (scalar(m.group(2)) if m.group(2) else None)


def parse_yaml(text):
    """Parse the front matter's YAML subset into nested dicts."""
    lines = []
    for raw in text.splitlines():
        line = strip_comment(raw)
        if line.strip():
            lines.append((len(line) - len(line.lstrip(" ")), line.strip()))
    out, _ = _block(lines, 0, 0)
    return out


def _block(lines, i, indent):
    out = {}
    while i < len(lines) and lines[i][0] >= indent:
        depth, content = lines[i]
        if depth > indent:
            raise ValueError(f"unexpected indent at {content!r}")
        key, value = key_value(content)
        i += 1
        if value is None and i < len(lines) and lines[i][0] > indent:
            value, i = _block(lines, i, lines[i][0])
        out[key] = value
    return out, i


def load(root=ROOT):
    return parse_yaml(front_matter((Path(root) / SPEC).read_text()))


# ---- colour ----------------------------------------------------------------------------------------------------

def oklch_to_linear(L, C, H):
    """OKLCH → linear sRGB (unclamped: a component outside 0–1 means out of gamut)."""
    h = math.radians(H)
    a, b = C * math.cos(h), C * math.sin(h)
    l_ = (L + 0.396338 * a + 0.215804 * b) ** 3
    m_ = (L - 0.105561 * a - 0.063854 * b) ** 3
    s_ = (L - 0.089484 * a - 1.291486 * b) ** 3
    return (4.076742 * l_ - 3.307712 * m_ + 0.230970 * s_,
            -1.268438 * l_ + 2.609757 * m_ - 0.341319 * s_,
            -0.004196 * l_ - 0.703419 * m_ + 1.707615 * s_)


def linear_to_oklab(rgb):
    r, g, b = rgb
    l_ = (0.412221 * r + 0.536333 * g + 0.051446 * b) ** (1 / 3)
    m_ = (0.211903 * r + 0.680700 * g + 0.107397 * b) ** (1 / 3)
    s_ = (0.088302 * r + 0.281719 * g + 0.629979 * b) ** (1 / 3)
    return (0.210454 * l_ + 0.793618 * m_ - 0.004072 * s_,
            1.977998 * l_ - 2.428592 * m_ + 0.450594 * s_,
            0.025904 * l_ + 0.782772 * m_ - 0.808676 * s_)


def in_gamut(L, C, H, eps=1e-4):
    return all(-eps <= c <= 1 + eps for c in oklch_to_linear(L, C, H))


def gamut_map(L, C, H):
    """Lower chroma until the colour fits sRGB. Never clips."""
    while C > 0 and not in_gamut(L, C, H):
        C = round(C - 0.001, 3)
    return max(C, 0.0)


def _encode(c):
    c = min(max(c, 0.0), 1.0)
    return 12.92 * c if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055


def _decode(c):
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def hex_of_linear(rgb):
    return "#" + "".join(f"{round(_encode(c) * 255):02X}" for c in rgb)


def oklch_hex(lch):
    return hex_of_linear(oklch_to_linear(*lch))


def rgb_of(hx):
    return [int(hx[i:i + 2], 16) / 255 for i in (1, 3, 5)]


def wcag(fg, bg):
    """WCAG 2 contrast ratio of two #RRGGBB colours."""
    def lum(hx):
        r, g, b = (_decode(c) for c in rgb_of(hx))
        return 0.2126 * r + 0.7152 * g + 0.0722 * b
    hi, lo = sorted((lum(fg), lum(bg)), reverse=True)
    return (hi + 0.05) / (lo + 0.05)


def apca(txt, bg):
    """APCA-W3 0.0.98G lightness contrast Lc (signed: negative is light text on dark)."""
    def y(hx):
        r, g, b = rgb_of(hx)
        v = 0.2126729 * r ** 2.4 + 0.7151522 * g ** 2.4 + 0.0721750 * b ** 2.4
        return v if v > 0.022 else v + (0.022 - v) ** 1.414
    yt, yb = y(txt), y(bg)
    if abs(yb - yt) < 0.0005:
        return 0.0
    if yb > yt:
        s = (yb ** 0.56 - yt ** 0.57) * 1.14
        return 0.0 if s < 0.1 else (s - 0.027) * 100
    s = (yb ** 0.65 - yt ** 0.62) * 1.14
    return 0.0 if s > -0.1 else (s + 0.027) * 100


def mix_hex(fg, bg, share):
    """`share` of fg over bg, mixed in OKLab."""
    a = linear_to_oklab([_decode(c) for c in rgb_of(fg)])
    b = linear_to_oklab([_decode(c) for c in rgb_of(bg)])
    L, A, B = (share * x + (1 - share) * y for x, y in zip(a, b))
    C, H = math.hypot(A, B), math.degrees(math.atan2(B, A)) % 360
    return oklch_hex((L, C, H))


# ---- resolving the spec ----------------------------------------------------------------------------------------

def lch(s):
    L, C, H = (float(x) for x in str(s).split())
    return L, C, H


def scales(spec):
    """{scale: {mode: [(L, C, H) × 12]}}: the primitives plus the derived accents."""
    out = {name: {m: [lch(s) for s in modes[m]] for m in MODES} for name, modes in spec["primitives"].items()}
    for name, hue in ACCENT_HUES.items():
        out[name] = {m: [(L, gamut_map(L, C, hue), float(hue)) for L, C, _ in out["signal"][m]] for m in MODES}
    return out


def palette(spec):
    """{scale: {mode: [#hex × 12]}}."""
    return {n: {m: [oklch_hex(c) for c in steps] for m, steps in modes.items()} for n, modes in scales(spec).items()}


def ref(value, mode, pal, accent="signal"):
    """`neutral.2`, `accent.9`, `ink`, `white` or `#RRGGBB` → #hex in `mode`."""
    v = str(value)
    if v.startswith("#"):
        return v.upper()
    if v == "white":
        return "#FFFFFF"
    if v == "ink":
        return pal["neutral"]["light"][11]
    scale, _, step = v.partition(".")
    scale = accent if scale == "accent" else scale
    if scale == "graphite":
        scale, step = "neutral", {"9": "12", "10": "11", "11": "12"}.get(step, step)
    if scale not in pal or not step.isdigit() or not 1 <= int(step) <= 12:
        raise ValueError(f"unknown colour reference {value!r}")
    return pal[scale][mode][int(step) - 1]


def colour_refs(spec):
    """{token path: {mode: reference}} for every semantic colour, e.g. 'status.needs.bg' → {'light': 'amber.3', …}."""
    out = {}
    def walk(node, path):
        for k, v in node.items():
            if k in ("hue", "glyph") or k == "increased_contrast":
                continue
            p = f"{path}.{k}" if path else k
            if isinstance(v, dict) and set(v) == set(MODES):
                out[p] = dict(v)
            elif isinstance(v, dict):
                walk(v, p)
            else:
                out[p] = {m: v for m in MODES}
    walk(spec["semantic"], "")
    return out


def resolve(spec, accent="signal"):
    """{token path: {mode: #hex}} for every semantic colour, with `accent` as the accent."""
    pal = palette(spec)
    refs = colour_refs(spec)
    out = {p: {m: ref(r[m], m, pal, accent) for m in MODES} for p, r in refs.items()}
    out["accent.on_solid"] = {m: (pal["neutral"][m][0] if accent == "graphite" else "#FFFFFF") for m in MODES}
    return out


def increased(spec, base):
    """The prefers-contrast: more overrides, as {token path: {mode: #hex}}."""
    pal, out = palette(spec), {}
    for path, value in spec["semantic"].get("increased_contrast", {}).items():
        m = re.match(r"(\S+) mixed (\d+)% over (\S+)", str(value))
        if m:
            out[path] = {md: mix_hex(ref(m.group(1), md, pal), base[m.group(3)][md], int(m.group(2)) / 100)
                         for md in MODES}
        elif re.fullmatch(r"[a-z]+\.\d+", str(value)):
            out[path] = {md: ref(value, md, pal) for md in MODES}
    return out


