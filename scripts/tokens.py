def _decls(pairs):
    return "".join(f"{k}:{v};" for k, v in pairs)


def mode_decls(spec, mode):
    """Every token whose value depends on the appearance: primitives, semantic colours, elevation."""
    pal = palette(spec)
    prim = [(f"--ds-{n}-{i + 1}", hx) for n, modes in pal.items() for i, hx in enumerate(modes[mode])]
    acc = [(f"--ds-accent-{i + 1}", f"var(--ds-signal-{i + 1})") for i in range(12)]
    sem = []
    for path, r in colour_refs(spec).items():
        v = str(r[mode])
        literal = v.startswith("#") or v in ("white", "ink")  # keywords resolve to a fixed colour, not a scale step
        sem.append((css_name(path), ref(v, mode, pal) if literal else f"var(--ds-{v.replace('.', '-')})"))
    sem.append(("--ds-accent-on-solid", "#FFFFFF"))
    elev = [(f"--ds-elevation-{k}", v if isinstance(v, str) else v[mode])
            for k, v in spec["elevation"].items() if k != "scrim"]
    elev.append(("--ds-elevation-scrim", spec["elevation"]["scrim"][mode]))
    return prim + acc + sem + elev


def static_decls(spec):
    """Tokens that are the same in both appearances: type, space, radius, motion, layout, ring."""
    t, out = spec["type"], []
    out += [("--ds-type-family-ui", "-apple-system,BlinkMacSystemFont,system-ui,sans-serif"),
            ("--ds-type-family-mono", 'ui-monospace,"SF Mono",Menlo,monospace')]
    for role, r in t["roles"].items():
        fam = "var(--ds-type-family-mono)" if r.get("family") == "mono" else "var(--ds-type-family-ui)"
        out += [(f"--ds-type-{role}", f"{r['weight']} {r['size']}px/{r['line']}px {fam}"),
                (f"--ds-type-{role}-size", f"{r['size']}px"),
                (f"--ds-type-{role}-track", f"{r.get('track', '0')}em".replace("+", ""))]
    out += [(f"--ds-space-{v}", f"{v}px") for v in spec["space"]]
    out += [(f"--ds-radius-{k}", f"{v}px") for k, v in spec["radius"].items() if isinstance(v, int)]
    out += [(f"--ds-duration-{k}", f"{v}" if isinstance(v, str) else f"{v}ms")
            for k, v in spec["motion"]["duration"].items()]
    out += [(f"--ds-easing-{k.replace('_', '-')}", v) for k, v in spec["motion"]["easing"].items()]
    out += [(f"--ds-layout-{_kebab(k)}", f"{v}px" if isinstance(v, int) else str(v)) for k, v in _flat(spec["layout"])]
    out.append(("--ds-ring", "0 0 0 2px var(--ds-bg-canvas),0 0 0 4px var(--ds-accent-ring)"))
    return out


def _kebab(path):
    return re.sub(r"[._]", "-", path)


def _flat(node, path=""):
    for k, v in node.items():
        p = f"{path}.{k}" if path else k
        if isinstance(v, dict):
            yield from _flat(v, p)
        else:
            yield p, v


def accent_rules():
    teal = _decls((f"--ds-accent-{i}", f"var(--ds-teal-{i})") for i in range(1, 13))
    graph = {9: 12, 10: 11, 11: 12}
    graphite = _decls((f"--ds-accent-{i}", f"var(--ds-neutral-{graph.get(i, i)})") for i in range(1, 13))
    return [f':root[data-accent="teal"]{{{teal}}}',
            f':root[data-accent="graphite"]{{{graphite}--ds-accent-on-solid:var(--ds-neutral-1);}}']


def alias_rule(page):
    aliases = ALIASES.get(page)
    if not aliases:
        return ""
    def target(path):
        if path.startswith("type.") and path.endswith(".size"):
            return f"var(--ds-type-{path[5:-5]}-size)"
        return f"var({css_name(path)})"
    return f':root[data-tokens="v2"]{{{_decls((k, target(v)) for k, v in aliases.items())}}}'


def css_block(spec, page):
    """The whole `<style id="ds-tokens">` element for one page."""
    base = resolve(spec)
    hc = increased(spec, base)
    hc_decls = lambda mode: _decls((css_name(p), v[mode]) for p, v in hc.items())  # noqa: E731
    ring_w = spec["semantic"].get("increased_contrast", {}).get("focus_ring_width")
    ring_hc = f"--ds-ring:0 0 0 2px var(--ds-bg-canvas),0 0 0 {2 + int(str(ring_w).rstrip('px'))}px var(--ds-accent-ring);" \
        if ring_w else ""
    rules = [f":root{{{_decls(static_decls(spec))}}}",
             f":root{{{_decls(mode_decls(spec, 'dark'))}}}",
             f"@media (prefers-color-scheme: light){{:root{{{_decls(mode_decls(spec, 'light'))}}}}}",
             f"@media (prefers-contrast: more){{:root{{{hc_decls('dark')}{ring_hc}}}}}",
             f"@media (prefers-contrast: more) and (prefers-color-scheme: light){{:root{{{hc_decls('light')}}}}}",
             *accent_rules(), alias_rule(page)]
    body = "\n".join(r for r in rules if r)
    return f"{OPEN}/* {NOTE} */\n{body}\n{CLOSE}"


def apply_block(html, block):
    """Replace the page's token block, or insert it before the first <style>."""
    if OPEN in html:
        start = html.index(OPEN)
        end = html.index(CLOSE, start) + len(CLOSE)
        return html[:start] + block + html[end:]
    at = html.index("<style")
    return html[:at] + block + "\n" + html[at:]


# ---- Swift -----------------------------------------------------------------------------------------------------

def camel(path):
    parts = re.split(r"[._-]", path)
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def _pair(p):
    return f"DSColor(light: 0x{p['light'][1:]}, dark: 0x{p['dark'][1:]})"


def swift_source(spec):
    """app/Sources/Tokens.swift."""
    base, hc = resolve(spec), increased(spec, resolve(spec))
    lines = [f"// {NOTE}.", "// Do not edit by hand. `tokens.py check` fails when this file and the spec disagree.",
             "import AppKit", "",
             "/// One colour token: its sRGB value in the light and the dark appearance.",
             "struct DSColor: Sendable {", "    let light: UInt32, dark: UInt32",
             "    func ns(dark isDark: Bool) -> NSColor {", "        let v = isDark ? dark : light",
             "        return NSColor(srgbRed: CGFloat(v >> 16 & 255) / 255, green: CGFloat(v >> 8 & 255) / 255, "
             "blue: CGFloat(v & 255) / 255, alpha: 1)", "    }", "}", "",
             "/// A type role: point size, line height, weight and tracking (CSS only; SF tracks itself).",
             "struct DSType: Sendable {", "    let size: CGFloat, line: CGFloat, weight: Int, track: CGFloat", "}", "",
             "enum DS {", "    enum Palette {"]
    lines += [f"        static let {camel(p)} = {_pair(v)}" for p, v in base.items()]
    lines += ["    }", "    /// Applied when Increase Contrast is on.", "    enum IncreasedContrast {"]
    lines += [f"        static let {camel(p)} = {_pair(v)}" for p, v in hc.items()]
    lines += ["    }"]
    for name in ("teal", "graphite"):
        acc = resolve(spec, name)
        lines += [f"    enum Accent{name.title()} {{"]
        lines += [f"        static let {camel(p[7:])} = {_pair(v)}" for p, v in acc.items() if p.startswith("accent.")]
        lines += ["    }"]
    lines += ["    enum TypeRole {"]
    for role, r in spec["type"]["roles"].items():
        track = float(str(r.get("track", 0)))
        lines.append(f"        static let {camel(role)} = DSType(size: {r['size']}, line: {r['line']}, "
                     f"weight: {r['weight']}, track: {track})")
    lines += ["    }", "    enum Space {"]
    lines += [f"        static let s{v}: CGFloat = {v}" for v in spec["space"]]
    lines += ["    }", "    enum Radius {"]
    lines += [f"        static let {k}: CGFloat = {v}" for k, v in spec["radius"].items() if isinstance(v, int)]
    lines += ["    }", "    /// Seconds.", "    enum Duration {"]
    lines += [f"        static let {k}: Double = {_seconds(v)}" for k, v in spec["motion"]["duration"].items()]
    lines += ["    }", "    /// cubic-bezier control points (x1, y1, x2, y2).", "    enum Easing {"]
    for k, v in spec["motion"]["easing"].items():
        m = re.match(r"cubic-bezier\((.*)\)", v)
        if m:
            pts = ", ".join(str(float(x)) for x in m.group(1).split(","))
            lines.append(f"        static let {camel(k)}: (Double, Double, Double, Double) = ({pts})")
    lines += ["    }", "    enum Layout {"]
    lines += [f"        static let {camel(p)}: CGFloat = {v}" for p, v in _flat(spec["layout"]) if isinstance(v, int)]
    lines += ["    }", "}", ""]
    return "\n".join(lines)


def _seconds(v):
    return float(str(v).removesuffix("ms") or 0) / 1000


# ---- checks ----------------------------------------------------------------------------------------------------

def check_gamut(spec):
    """Every primitive must already fit sRGB: the spec lowers chroma itself, so nothing is ever clipped."""
    errs = []
    for name, modes in spec["primitives"].items():
        for mode in MODES:
            for i, s in enumerate(modes[mode]):
                if not in_gamut(*lch(s)):
                    errs.append(f"{name}.{mode}.{i + 1} ({s}) is outside sRGB: lower its chroma")
    return errs


def check_hex_notes(text, spec):
    """The `# light sRGB: …` notes under each scale in the spec must match what the generator computes."""
    errs, pal = [], palette(spec)
    for mode, hexes in re.findall(r"^\s*#\s*(light|dark) sRGB:\s*([#0-9A-Fa-f ]+)$", text, re.M):
        if hexes.upper().split() not in [p[mode] for p in pal.values()]:
            errs.append(f"the spec's '{mode} sRGB: {hexes.split()[0]} …' note matches no computed {mode} scale")
    return errs


def check_scales(spec):
    """Step 11 ≥ APCA Lc 60 and step 12 ≥ Lc 90 on step 2, on every scale in both modes."""
    errs = []
    for name, modes in palette(spec).items():
        for mode, hx in modes.items():
            for step, floor in ((11, 60), (12, 90)):
                lc = abs(apca(hx[step - 1], hx[1]))
                if lc < floor:
                    errs.append(f"{name}.{mode}: step {step} on step 2 is APCA Lc {lc:.1f}, needs {floor}")
    return errs


def check_pairs(spec):
    """Text tokens against the surfaces they sit on, at WCAG AA (4.5:1)."""
    errs = []
    for accent in ("signal", *ACCENT_HUES, "graphite"):
        c = resolve(spec, accent)
        pairs = [("accent.on_solid", "accent.solid"), ("accent.fg", "bg.surface"), ("accent.fg", "bg.canvas")]
        if accent == "signal":
            pairs += [(fg, bg) for fg in ("fg.default", "fg.muted") for bg in c if bg.startswith("bg.")]
            pairs += [(f"status.{s}.fg", bg) for s in spec["semantic"]["status"] for bg in ("bg.surface", "bg.canvas")]
            pairs += [(f"status.{s}.on_solid", f"status.{s}.solid") for s in spec["semantic"]["status"]
                      if f"status.{s}.on_solid" in c]
            pairs += [(f"diff.{k}.fg", f"diff.{k}.bg") for k in spec["semantic"].get("diff", {})]
        for fg, bg in pairs:
            for mode in MODES:
                ratio = wcag(c[fg][mode], c[bg][mode])
                if ratio < 4.5:
                    errs.append(f"[{accent}] {fg} on {bg} ({mode}) is {ratio:.2f}:1, needs 4.5:1")
    return errs


def check_accents():
    """No accent hue near a status hue, nor violet (270–330)."""
    errs = []
    for name, hue in {"signal": 150, **ACCENT_HUES}.items():
        near = [s for s in STATUS_HUES if min(abs(hue - s), 360 - abs(hue - s)) < 25]
        if near or 270 <= hue <= 330:
            errs.append(f"accent {name} (hue {hue}) is too close to a status hue or violet")
    return errs


def expected(spec, root=ROOT):
    """{relative path: generated content} for every file the generator owns."""
    out = {page: apply_block((Path(root) / page).read_text(), css_block(spec, page)) for page in PAGES}
    out[SWIFT] = swift_source(spec)
    return out


def check_stale(spec, root=ROOT):
    errs = []
    for rel, want in expected(spec, root).items():
        path = Path(root) / rel
        if not path.exists() or path.read_text() != want:
            errs.append(f"{rel} is out of date with {SPEC}: run `python3 scripts/tokens.py generate`")
    return errs


def run_check(root=ROOT):
    text = (Path(root) / SPEC).read_text()
    spec = parse_yaml(front_matter(text))
    return (check_gamut(spec) + check_hex_notes(text, spec) + check_scales(spec) + check_pairs(spec)
            + check_accents() + check_stale(spec, root))


def generate(root=ROOT):
    """Write every generated file; returns the paths that changed."""
    changed = []
    for rel, want in expected(load(root), root).items():
        path = Path(root) / rel
        if not path.exists() or path.read_text() != want:
            path.write_text(want)
            changed.append(rel)
    return changed


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("cmd", choices=("generate", "check"))
    ap.add_argument("--root", default=str(ROOT), help=argparse.SUPPRESS)
    args = ap.parse_args(argv)
    root = Path(args.root)
    with diag.span("tokens", op=args.cmd) as sp:
        if args.cmd == "generate":
            changed = generate(root)
            sp["rows"] = len(changed)
            print("\n".join(f"wrote {c}" for c in changed) or "ok  tokens already up to date")
            return 0
        errs = run_check(root)
        sp["rows"] = len(errs)
    for e in errs:
        print(f"TOKENS FAIL: {e}", file=sys.stderr)
    if not errs:
        print(f"ok  tokens match {SPEC} (gamut, APCA scales, WCAG pairs, accents, generated files)")
    return 1 if errs else 0


if __name__ == "__main__":
    diag.install("tokens")
    sys.exit(main())
