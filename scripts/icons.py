#!/usr/bin/env python3
"""Greenlight's interface icons: brand/icons/{ui,marks}/*.svg → the pages and Swift (DESIGN.md §9).

    python3 scripts/icons.py generate        # rewrite the <script id="ds-icons"> blocks and app/Sources/Icons.swift
    python3 scripts/icons.py check           # fail on a malformed icon, an unknown or unused name, or stale output
    python3 scripts/icons.py sheet OUT.html  # a contact sheet: every icon at 1× and 2×, light and dark

ui/ icons are drawn once on a 16 grid with a 1.5 stroke, round caps and joins, and currentColor. Names ending in
`-fill` are the filled variants (selected states, status glyphs at 12px and under). marks/ holds the agents' brand marks
(24 grid, filled). Both runtimes render them at any size with a constant on-screen stroke: 1.5px, or 1.75px for the
Medium weight beside 600-weight text.
"""
import argparse
import html
import json
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import diag  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
SETS = {"brand/icons/ui": 16, "brand/icons/marks": 24}
PAGES = ("app/dashboard.html", "app/terminal.html")
SWIFT = "app/Sources/Icons.swift"
OPEN, CLOSE = '<script id="ds-icons">', "</script><!-- /ds-icons -->"
NOTE = "generated by scripts/icons.py from brand/icons: edit the SVGs, then run `icons.py generate`"
NS = "{http://www.w3.org/2000/svg}"
STROKE_ROOT = {"fill": "none", "stroke": "currentColor", "stroke-width": "1.5", "stroke-linecap": "round",
               "stroke-linejoin": "round"}
FILL_ROOT = {"fill": "currentColor", "stroke": "none"}
TAGS = {"path", "circle", "rect", "line", "polyline", "polygon", "ellipse"}
ATTRS = {"d", "cx", "cy", "r", "rx", "ry", "x", "y", "width", "height", "x1", "y1", "x2", "y2", "points",
         "fill-rule", "stroke-dasharray", "fill", "stroke"}
PAINT = {"currentColor", "none"}
# Calls whose first argument names icons: every quoted name in it (a literal, or both arms of a ternary) must exist.
CALLS = re.compile(r"(?<![\w.])(?:dsIcon|dsIconHTML|ico|icon|g16|DSIcon\.image|banner|pathRow|knob)\(|Image\(ds:|"
                   r"\blistItem\(.*?\bicon:")
# The pages' name maps (a meaning → an icon): every value must exist.
MAPS = re.compile(r"\bconst (?:GLYPH|MI|G) = \{([^}]*)\}")
NAME = re.compile(r"""["']([a-z0-9]+(?:-[a-z0-9]+)*)["']""")
GENERATED = re.compile(r'<script id="ds-icons">.*?</script><!-- /ds-icons -->', re.S)


# ---- reading and validating ------------------------------------------------------------------------------------

def parse_icon(path, grid):
    """(name, record, errors) for one SVG. record = [grid, 's'|'f', [[tag, {attrs}], ...]]."""
    name, errs = path.stem, []
    if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", name):
        errs.append(f"{path.name}: names are lowercase words joined by '-'")
    try:
        root = ET.parse(path).getroot()  # noqa: S314 - the repo's own icon sources, not outside input; stdlib only
    except ET.ParseError as e:
        return name, None, [f"{path.name}: not valid SVG ({e})"]
    filled = name.endswith("-fill") or grid == 24
    want = {**(FILL_ROOT if filled else STROKE_ROOT), "viewBox": f"0 0 {grid} {grid}"}
    got = {k: v for k, v in root.attrib.items()}
    if got != want:
        errs.append(f"{path.name}: the <svg> must carry exactly {want}, not {got}")
    els = []
    for el in root:
        tag = el.tag.replace(NS, "")
        bad = set(el.attrib) - ATTRS
        if tag not in TAGS:
            errs.append(f"{path.name}: <{tag}> isn't allowed (use {', '.join(sorted(TAGS))})")
        if bad:
            errs.append(f"{path.name}: <{tag}> has disallowed attributes {sorted(bad)} (no transform, style, ids, widths)")
        paint = {el.attrib[k] for k in ("fill", "stroke") if k in el.attrib}
        if paint - PAINT:
            errs.append(f"{path.name}: colours must be currentColor or none, not {sorted(paint - PAINT)}")
        if len(el):
            errs.append(f"{path.name}: <{tag}> can't have children (no groups)")
        els.append([tag, dict(el.attrib)])
    if not els:
        errs.append(f"{path.name}: draws nothing")
    return name, [grid, "f" if filled else "s", els], errs


def load(root=ROOT):
    """({name: record}, errors) across every icon set."""
    icons, errs = {}, []
    for rel, grid in SETS.items():
        for path in sorted((Path(root) / rel).glob("*.svg")):
            name, rec, e = parse_icon(path, grid)
            errs += e
            if name in icons:
                errs.append(f"{rel}/{path.name}: '{name}' is defined twice")
            if rec:
                icons[name] = rec
    return icons, errs


# ---- output ----------------------------------------------------------------------------------------------------

JS = """
// Icon `name` as an <svg>. Strokes stay 1.5px on screen at 16px and up (1.75px with {medium: true}) and scale down below it.
function dsIcon(name, px = 16, opts = {}){
  const NS = "http://www.w3.org/2000/svg", i = DS_ICONS[name] || DS_ICONS.question, e = document.createElementNS(NS, "svg");
  const a = {width: px, height: px, viewBox: `0 0 ${i[0]} ${i[0]}`, class: ("dsi " + (opts.cls || "")).trim(), "data-icon": DS_ICONS[name] ? name : "question", "aria-hidden": "true"};
  if (i[1] === "s") Object.assign(a, {fill: "none", stroke: "currentColor", "stroke-width": String(+((opts.medium ? 1.75 : 1.5) * 16 / Math.max(px, 16)).toFixed(3)), "stroke-linecap": "round", "stroke-linejoin": "round"});
  else a.fill = "currentColor";
  for (const k in a) e.setAttribute(k, a[k]);
  for (const [tag, at] of i[2]){ const c = document.createElementNS(NS, tag); for (const k in at) c.setAttribute(k, at[k]); e.append(c) }
  return e;
}
function dsIconHTML(name, px = 16, opts = {}){ return dsIcon(name, px, opts).outerHTML }
"""


def js_block(icons):
    data = json.dumps(icons, separators=(",", ":"), sort_keys=True)
    return (f"{OPEN}/* {NOTE}. The agent marks (claude, openai) are from lobe-icons, MIT: "
            f"brand/icons/marks/LICENSE.lobe-icons */\nconst DS_ICONS = {data};{JS}{CLOSE}")


def apply_block(text, block):
    """Replace the page's icon block, or insert it before the page's first <script>."""
    if text.count(OPEN) > 1:
        raise ValueError(f"the page has more than one {OPEN} block")
    if OPEN in text:
        out, n = GENERATED.subn(lambda _m: block, text, count=1)
        if not n:
            raise ValueError(f"the page has {OPEN} but not its end marker {CLOSE}")
        return out
    at = text.index("<script")
    return text[:at] + block + "\n" + text[at:]


def swift_markup(els):
    out = []
    for tag, attrs in els:
        a = " ".join(f'{k}="{html.escape(v.replace("currentColor", "black"))}"' for k, v in attrs.items())
        out.append(f"<{tag} {a}/>")
    return "".join(out).replace("\\", "\\\\").replace('"', '\\"')


def swift_source(icons):
    rows = "\n".join(f'        "{n}": ({g}, {str(k == "s").lower()}, "{swift_markup(els)}"),'
                     for n, (g, k, els) in sorted(icons.items()))
    return f"""// {NOTE}.
// Do not edit by hand. `icons.py check` fails when this file and brand/icons disagree.
import AppKit
import SwiftUI

enum DSIcons {{
    /// name → (grid, stroked, inner SVG markup in black for a template image)
    static let all: [String: (Int, Bool, String)] = [
{rows}
    ]
}}

/// Greenlight's icons as template NSImages, cached per name, size and weight.
enum DSIcon {{
    nonisolated(unsafe) private static let cache = NSCache<NSString, NSImage>()

    /// Strokes stay 1.5pt on screen at 16pt and up (1.75pt when `medium`) and scale down below it, as on the web.
    static func image(_ name: String, size: CGFloat = 16, medium: Bool = false) -> NSImage {{
        let key = "\\(name)@\\(size)\\(medium ? "m" : "")" as NSString
        if let hit = cache.object(forKey: key) {{ return hit }}
        let (grid, stroked, inner) = DSIcons.all[name] ?? DSIcons.all["question"] ?? (16, true, "")
        let w = (medium ? 1.75 : 1.5) * 16 / max(size, 16)
        let paint = stroked
            ? "fill=\\"none\\" stroke=\\"black\\" stroke-width=\\"\\(w)\\" stroke-linecap=\\"round\\" stroke-linejoin=\\"round\\""
            : "fill=\\"black\\""
        let svg = "<svg xmlns=\\"http://www.w3.org/2000/svg\\" width=\\"\\(size)\\" height=\\"\\(size)\\" viewBox=\\"0 0 \\(grid) \\(grid)\\" \\(paint)>\\(inner)</svg>"
        let img = NSImage(data: Data(svg.utf8)) ?? NSImage(size: NSSize(width: size, height: size))
        img.isTemplate = true
        img.size = NSSize(width: size, height: size)
        cache.setObject(img, forKey: key)
        return img
    }}
}}

extension Image {{
    /// An icon from Greenlight's set, `size` points square, tinted by `.foregroundColor` like an SF Symbol.
    init(ds name: String, size: CGFloat = 16, medium: Bool = false) {{
        self.init(nsImage: DSIcon.image(name, size: size, medium: medium))
        // NSImage.isTemplate makes SwiftUI tint it with the foreground colour
    }}
}}
"""


def expected(icons, root=ROOT):
    out = {page: apply_block((Path(root) / page).read_text(), js_block(icons)) for page in PAGES}
    out[SWIFT] = swift_source(icons)
    return out


# ---- usage -----------------------------------------------------------------------------------------------------

def sources(root=ROOT):
    """{relative path: text} of the code that uses icons, minus the generated parts."""
    root, out = Path(root), {}
    for page in PAGES:
        out[page] = GENERATED.sub("", (root / page).read_text())
    for path in sorted((root / "app/Sources").glob("*.swift")):
        if path.name != Path(SWIFT).name:
            out[str(path.relative_to(root))] = path.read_text()
    return out


def first_arg(text, i):
    """The source of the call argument starting at text[i]: up to its top-level `,` or closing bracket."""
    depth, quote, j = 0, None, i
    while j < len(text):
        c = text[j]
        if quote:
            j += c == "\\"
            quote = None if c == quote else quote
        elif c in "\"'`":
            quote = c
        elif c in "([{":
            depth += 1
        elif c in ")]}" and depth == 0 or c == "," and depth == 0:
            break
        elif c in ")]}":
            depth -= 1
        j += 1
    return text[i:j]


def named(text):
    """(offset, name) for every icon name the text passes to an icon call or puts in a name map."""
    for m in CALLS.finditer(text):
        yield from ((m.start(), n) for n in NAME.findall(first_arg(text, m.end())))
    for m in MAPS.finditer(text):
        yield from ((m.start(), v) for v in re.findall(r""":\s*["']([a-z0-9-]+)["']""", m.group(1)))


def reserved(root=ROOT):
    """The status glyphs DESIGN.md's front matter names: part of the set before a surface draws them."""
    spec = Path(root) / "brand/DESIGN.md"
    return set(re.findall(r"\bglyph: ([a-z0-9-]+)", spec.read_text())) if spec.exists() else set()


def check_usage(icons, root=ROOT):
    """Every name an icon call or name map gives exists, and every icon is named somewhere (or reserved by the spec).

    For "named somewhere" any quoted string equal to the icon's name counts, so the Swift tables of (pane, icon, …)
    count too; the price is that a short name that's also a state or command string can go dead unseen.
    """
    errs, texts = [], sources(root)
    for rel, text in texts.items():
        for at, name in named(text):
            if name not in icons:
                errs.append(f"{rel}:{text.count(chr(10), 0, at) + 1}: no icon named '{name}' in brand/icons")
    everything, keep = "\n".join(texts.values()), reserved(root)
    errs.extend(f"brand/icons: '{name}' is never used; delete it or use it" for name in sorted(icons)
                if name != "question" and name not in keep and not re.search(rf"""["']{re.escape(name)}["']""", everything))
    return errs


def run_check(root=ROOT):
    icons, errs = load(root)
    if "question" not in icons:
        errs.append("brand/icons/ui/question.svg is the fallback for unknown names and must exist")
    errs += check_usage(icons, root)
    try:
        want_all = expected(icons, root)
    except ValueError as e:
        return [*errs, str(e)]
    for rel, want in want_all.items():
        path = Path(root) / rel
        if not path.exists() or path.read_text() != want:
            errs.append(f"{rel} is out of date with brand/icons: run `python3 scripts/icons.py generate`")
    return errs


def generate(root=ROOT):
    icons, errs = load(root)
    if errs:
        raise ValueError("; ".join(errs))
    changed = []
    for rel, want in expected(icons, root).items():
        path = Path(root) / rel
        if not path.exists() or path.read_text() != want:
            path.write_text(want)
            changed.append(rel)
    return changed


def sheet(icons):
    """A contact sheet: each icon at 16px (1×), at 16px on a 2× scale, and at 64px, on light and dark."""
    def svg(name, px):
        g, k, els = icons[name]
        paint = 'fill="currentColor"' if k == "f" else \
            f'fill="none" stroke="currentColor" stroke-width="{1.5 * 16 / max(px, 16):g}" stroke-linecap="round" stroke-linejoin="round"'
        inner = "".join(f"<{t} " + " ".join(f'{a}="{html.escape(v)}"' for a, v in at.items()) + "/>" for t, at in els)
        return f'<svg width="{px}" height="{px}" viewBox="0 0 {g} {g}" {paint}>{inner}</svg>'
    cells = "".join(f'<figure>{svg(n, 64)}<div>{svg(n, 16)}<span class="x2">{svg(n, 16)}</span></div>'
                    f'<figcaption>{n}</figcaption></figure>' for n in sorted(icons))
    css = ("body{margin:0;font:11px -apple-system,system-ui,sans-serif;display:grid;grid-template-columns:1fr 1fr}"
           "section{padding:16px;display:grid;grid-template-columns:repeat(8,1fr);gap:6px;align-content:start}"
           ".light{background:#FAFEFB;color:#1B1F1C}.dark{background:#0E100F;color:#EAF0EC}"
           "figure{margin:0;display:flex;flex-direction:column;align-items:center;gap:4px;padding:6px}"
           "figure div{display:flex;gap:10px;align-items:center}.x2{zoom:2}figcaption{opacity:.7}")
    return (f"<!doctype html><meta charset=utf-8><title>Greenlight icons</title><style>{css}</style>"
            f'<section class="light">{cells}</section><section class="dark">{cells}</section>')


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("cmd", choices=("generate", "check", "sheet"))
    ap.add_argument("out", nargs="?", help="sheet: where to write the HTML")
    ap.add_argument("--root", default=str(ROOT), help=argparse.SUPPRESS)
    args = ap.parse_args(argv)
    root = Path(args.root)
    with diag.span("icons", op=args.cmd) as sp:
        if args.cmd == "sheet":
            Path(args.out or "icons.html").write_text(sheet(load(root)[0]))
            return 0
        if args.cmd == "generate":
            changed = generate(root)
            sp["rows"] = len(changed)
            print("\n".join(f"wrote {c}" for c in changed) or "ok  icons already up to date")
            return 0
        errs = run_check(root)
        sp["rows"] = len(errs)
    for e in errs:
        print(f"ICONS FAIL: {e}", file=sys.stderr)
    if not errs:
        print(f"ok  icons match brand/icons ({len(load(root)[0])} icons: grid, stroke, paint, usage, generated files)")
    return 1 if errs else 0


if __name__ == "__main__":
    diag.install("icons")
    sys.exit(main())
